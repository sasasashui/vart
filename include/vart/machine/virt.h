#ifndef VART_MACHINE_VIRT_H
#define VART_MACHINE_VIRT_H

#include <stdint.h>

#define VART_VIRT_DEBUG_BASE UINT64_C(0x00000000)
#define VART_VIRT_DEBUG_SIZE UINT64_C(0x00000100)
#define VART_VIRT_MROM_BASE UINT64_C(0x00001000)
#define VART_VIRT_MROM_SIZE UINT64_C(0x0000f000)
#define VART_VIRT_TEST_BASE UINT64_C(0x00100000)
#define VART_VIRT_TEST_SIZE UINT64_C(0x00001000)
#define VART_VIRT_RTC_BASE UINT64_C(0x00101000)
#define VART_VIRT_RTC_SIZE UINT64_C(0x00001000)
#define VART_VIRT_PCIE_PIO_BASE UINT64_C(0x03000000)
#define VART_VIRT_PCIE_PIO_SIZE UINT64_C(0x00010000)
#define VART_VIRT_IOMMU_BASE UINT64_C(0x03010000)
#define VART_VIRT_IOMMU_SIZE UINT64_C(0x00001000)
#define VART_VIRT_PLATFORM_BASE UINT64_C(0x04000000)
#define VART_VIRT_PLATFORM_SIZE UINT64_C(0x02000000)
#define VART_VIRT_APLIC_M_BASE UINT64_C(0x0c000000)
#define VART_VIRT_APLIC_S_BASE UINT64_C(0x0d000000)
#define VART_VIRT_UART_BASE UINT64_C(0x10000000)
#define VART_VIRT_UART_SIZE UINT64_C(0x00000100)
#define VART_VIRT_UART_IRQ 10
#define VART_VIRT_VIRTIO_BASE UINT64_C(0x10001000)
#define VART_VIRT_VIRTIO_SIZE UINT64_C(0x00001000)
#define VART_VIRT_FLASH_BASE UINT64_C(0x20000000)
#define VART_VIRT_FLASH_SIZE UINT64_C(0x04000000)
#define VART_VIRT_IMSIC_M_BASE UINT64_C(0x24000000)
#define VART_VIRT_IMSIC_S_BASE UINT64_C(0x28000000)
#define VART_VIRT_IMSIC_MAX_SIZE UINT64_C(0x04000000)
#define VART_VIRT_IMSIC_GROUP_SIZE UINT64_C(0x01000000)
#define VART_VIRT_IMSIC_FILE_SIZE UINT64_C(0x00001000)
#define VART_VIRT_PCIE_ECAM_BASE UINT64_C(0x30000000)
#define VART_VIRT_PCIE_ECAM_SIZE UINT64_C(0x10000000)
#define VART_VIRT_PCIE_MMIO_BASE UINT64_C(0x40000000)
#define VART_VIRT_PCIE_MMIO_SIZE UINT64_C(0x40000000)
#define VART_VIRT_DRAM_BASE UINT64_C(0x80000000)

static inline uint64_t vart_virt_imsic_hart_size(unsigned int guest_bits)
{
    return VART_VIRT_IMSIC_FILE_SIZE << guest_bits;
}

static inline uint64_t vart_virt_imsic_hart_base(uint64_t domain_base,
                                                 unsigned int group,
                                                 unsigned int hart,
                                                 unsigned int guest_bits)
{
    return domain_base + group * VART_VIRT_IMSIC_GROUP_SIZE +
           hart * vart_virt_imsic_hart_size(guest_bits);
}

#endif
